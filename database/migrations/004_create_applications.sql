-- Job applications from the public Apply Now form (plan.md §4.1).
CREATE TABLE applications (
    id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    reference_no VARCHAR(25) NOT NULL,
    full_name VARCHAR(100) NOT NULL,
    father_name VARCHAR(100) NOT NULL,
    date_of_birth DATE NOT NULL,
    age_at_submission TINYINT UNSIGNED NOT NULL,
    gender ENUM('male', 'female') NOT NULL,
    nid_no VARCHAR(17) NULL,
    mobile VARCHAR(20) NOT NULL,
    email VARCHAR(150) NULL,
    present_address VARCHAR(255) NOT NULL,
    job_category_id INT UNSIGNED NOT NULL,
    work_experience VARCHAR(20) NULL,
    education_level VARCHAR(20) NULL,
    passport_status ENUM('have_passport', 'will_apply') NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'received',
    is_age_flagged TINYINT(1) NOT NULL DEFAULT 0,
    is_duplicate_flagged TINYINT(1) NOT NULL DEFAULT 0,
    declaration_accepted_at DATETIME NOT NULL,
    ip_address VARCHAR(45) NOT NULL,
    user_agent VARCHAR(255) NOT NULL DEFAULT '',
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    deleted_at DATETIME NULL,
    UNIQUE KEY uq_applications_reference (reference_no),
    KEY idx_applications_status_created (status, created_at),
    KEY idx_applications_mobile (mobile),
    KEY idx_applications_nid (nid_no),
    KEY idx_applications_category (job_category_id),
    KEY idx_applications_deleted (deleted_at),
    CONSTRAINT fk_applications_category FOREIGN KEY (job_category_id) REFERENCES job_categories (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
